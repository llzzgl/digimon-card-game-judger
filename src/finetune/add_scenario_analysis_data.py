"""
添加场面分析训练数据
用于训练模型进行复杂场面推理和规则综合应用
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))

from data_collector import DTCGDataCollector


def add_scenario_analysis_examples(collector: DTCGDataCollector):
    """添加场面分析示例"""
    
    # 场面分析的系统指令
    scenario_instruction = """你是数码宝贝卡牌游戏(DTCG)的规则专家和裁判。
请分析给定的游戏场面，综合考虑：
1. 涉及的卡牌效果
2. 相关的规则条款
3. 效果的触发时机和处理顺序
4. 最终的场面结果

给出详细的分析过程和结论。"""
    
    # 示例1: 联展 + 退化 + 效果触发
    scenario_1 = {
        "question": """我方联展了bt23-032土偶兽，把对方的数码兽退化成bt24-016拉米亚兽，并选择其主要阶段开始时攻击。
土偶进化源中有bt23-027天使兽和bt23-050甲龙兽。
对方拉米亚进化源中有bt21-001基基兽。
此时移交回合后会发生什么？""",
        
        "answer": """让我分析这个复杂场面：

【涉及的卡牌效果】
1. BT23-032 土偶兽：联展效果，可以退化对手数码兽并选择其主要阶段开始时攻击
2. BT24-016 拉米亚兽：【主要阶段开始时】效果（需要确认具体效果）
3. BT23-027 天使兽：进化源效果（需要确认）
4. BT23-050 甲龙兽：进化源效果（需要确认）
5. BT21-001 基基兽：进化源效果（需要确认）

【关键规则】
• 规则 15-8-3：触发型效果在满足触发条件后触发，进入发动等待状态
• 规则 15-9：多个效果同时触发时，按"回合玩家效果→非回合玩家效果"的顺序发动
• 规则 6-1-4：回合结束条件是内存对手方1以上且没有需要结算的处理

【处理流程】
1. 土偶兽联展效果结算，拉米亚兽被退化
2. 土偶兽选择拉米亚兽的【主要阶段开始时】效果攻击
3. 移交回合，变为对手回合
4. 对手回合的主要阶段开始时：
   - 拉米亚兽的【主要阶段开始时】效果触发
   - 土偶兽进化源中的天使兽和甲龙兽的【主要阶段开始时】效果也会触发（如果有）
   - 拉米亚兽进化源中的基基兽效果也会触发（如果有）
5. 按照"回合玩家效果→非回合玩家效果"顺序：
   - 先处理对手的拉米亚兽和基基兽的效果
   - 再处理我方土偶兽进化源的效果

【结论】
移交回合后，在对手的主要阶段开始时，会依次触发和结算所有【主要阶段开始时】效果。
具体结果取决于这些卡牌的实际效果内容。

【建议】
这是一个复杂的效果链，建议：
1. 确认所有涉及卡牌的完整效果文本
2. 按照触发顺序逐个结算
3. 如有疑问，以官方裁定为准"""
    }

    
    collector.add_custom_qa(
        question=scenario_1["question"],
        answer=scenario_1["answer"],
        instruction=scenario_instruction,
        tags=["场面分析", "联展", "退化", "效果触发顺序"]
    )
    
    # 示例2: 效果触发时机
    scenario_2 = {
        "question": """对手用数码兽攻击我，我的安防中翻出了一张有安防效果的卡。
这张卡的安防效果是"消灭攻击中的数码兽"。
请问这个效果能阻止我的安防被判定吗？""",
        
        "answer": """【涉及规则】
• 规则 13-1：判定安防的流程
• 规则 15-8-5：即时型效果的处理

【分析】
1. 判定安防流程：
   - 翻开安防卡
   - 如果有安防效果，立即发动
   - 安防效果结算完成后，将该卡加入手牌
   - 判定安防结束

2. 安防效果"消灭攻击中的数码兽"：
   - 这是一个即时型效果
   - 在判定安防过程中发动
   - 如果成功消灭攻击中的数码兽，攻击结束

【结论】
不能阻止安防被判定。因为：
1. 安防已经被翻开（判定已经发生）
2. 安防效果是在判定过程中发动的
3. 即使消灭了攻击中的数码兽，这次判定仍然完成
4. 该安防卡会加入手牌

但是，如果攻击中的数码兽被消灭：
- 攻击立即结束
- 不会继续判定更多安防（如果有≪安防攻击≫）
- 攻击结束时的效果不会触发"""
    }
    
    collector.add_custom_qa(
        question=scenario_2["question"],
        answer=scenario_2["answer"],
        instruction=scenario_instruction,
        tags=["场面分析", "安防效果", "效果时机"]
    )
    
    # 示例3: 效果处理顺序
    scenario_3 = {
        "question": """我的数码兽攻击对手，对战中消灭了对手的数码兽。
我的数码兽有≪贯通≫效果，同时有【消灭对手数码兽时】的效果。
请问这两个效果如何处理？""",
        
        "answer": """【涉及规则】
• 规则 16-6：≪贯通≫效果
• 规则 15-9：多个效果同时触发的处理顺序
• 规则 11-3：攻击流程

【分析】
1. 对战结算，对手数码兽被消灭
2. 此时同时触发两个效果：
   - ≪贯通≫：在攻击结束时之前判定安防
   - 【消灭对手数码兽时】：触发型效果

3. 处理顺序：
   - ≪贯通≫是关键词效果，在特定时机自动处理
   - 【消灭对手数码兽时】是触发型效果，进入发动等待
   - 先处理≪贯通≫的判定安防
   - 然后在攻击结束时处理【消灭对手数码兽时】效果

【结论】
处理顺序：
1. 对战结算，消灭对手数码兽
2. ≪贯通≫触发，判定对手安防
3. 判定安防结束
4. 【消灭对手数码兽时】效果发动
5. 攻击结束

【注意】
如果【消灭对手数码兽时】效果会影响判定安防（比如"不判定安防"），
则需要在≪贯通≫之前处理。具体以卡牌效果文本为准。"""
    }
    
    collector.add_custom_qa(
        question=scenario_3["question"],
        answer=scenario_3["answer"],
        instruction=scenario_instruction,
        tags=["场面分析", "贯通", "效果顺序", "对战"]
    )

    
    # 示例4: 进化源效果
    scenario_4 = {
        "question": """我的数码兽进化源中有一张卡，效果是"【你的回合】此数码兽DP+1000"。
请问这个效果什么时候生效？如果我把这张卡从进化源移除，效果会消失吗？""",
        
        "answer": """【涉及规则】
• 规则 15-3：进化源效果
• 规则 15-4：持续型效果

【分析】
1. 进化源效果的特性：
   - 由数码兽获得，不是由进化源卡牌本身发动
   - 只要卡牌在进化源中，数码兽就持续获得该效果
   - 效果中的"此数码兽"指的是获得效果的数码兽

2. "【你的回合】此数码兽DP+1000"：
   - 这是一个持续型效果
   - 在你的回合期间持续生效
   - 在对手回合不生效

3. 移除进化源的影响：
   - 如果这张卡从进化源移除，数码兽立即失去该效果
   - DP加成立即消失
   - 如果因此DP变为0以下，数码兽被消灭

【结论】
• 效果在你的回合期间生效，数码兽DP+1000
• 对手回合期间不生效
• 如果卡牌离开进化源，效果立即消失

【示例】
假设数码兽基础DP是3000：
- 你的回合：DP = 4000
- 对手回合：DP = 3000
- 进化源被移除后：DP = 3000（无论哪个回合）"""
    }
    
    collector.add_custom_qa(
        question=scenario_4["question"],
        answer=scenario_4["answer"],
        instruction=scenario_instruction,
        tags=["场面分析", "进化源效果", "持续型效果"]
    )
    
    # 示例5: 多个效果同时触发
    scenario_5 = {
        "question": """我的回合开始时，我有3只数码兽，都有【你的回合开始时】效果。
对手也有1只数码兽有【对手回合开始时】效果。
请问这些效果如何处理？""",
        
        "answer": """【涉及规则】
• 规则 15-9：多个效果同时触发的处理
• 规则 6-1：回合流程

【分析】
1. 回合开始时，同时触发4个效果：
   - 我方3个【你的回合开始时】效果
   - 对手1个【对手回合开始时】效果

2. 处理顺序规则：
   - 回合玩家的效果优先处理
   - 同一玩家的多个效果，由该玩家选择处理顺序

【处理流程】
1. 首先处理我方（回合玩家）的3个效果：
   - 我选择这3个效果的处理顺序
   - 逐个发动和结算

2. 然后处理对手（非回合玩家）的1个效果：
   - 对手的效果发动和结算

3. 所有效果结算完成后，继续回合流程

【结论】
处理顺序：
1. 我方效果1（我选择）
2. 我方效果2（我选择）
3. 我方效果3（我选择）
4. 对手效果

【注意】
- 每个效果结算时，可能触发新的效果
- 新触发的效果会在当前效果结算后立即处理
- 如果效果结算中场面发生变化，后续效果可能无法发动"""
    }
    
    collector.add_custom_qa(
        question=scenario_5["question"],
        answer=scenario_5["answer"],
        instruction=scenario_instruction,
        tags=["场面分析", "效果顺序", "回合开始时"]
    )
    
    print(f"✅ 添加了 5 个场面分析示例")


def main():
    """主函数"""
    print("=" * 60)
    print("添加场面分析训练数据")
    print("=" * 60)
    
    # 初始化收集器
    collector = DTCGDataCollector(output_dir="training_data")
    
    # 添加场面分析示例
    add_scenario_analysis_examples(collector)
    
    # 显示统计
    collector.print_statistics()
    
    # 导出数据
    collector.export_jsonl("scenario_analysis_data.jsonl")
    collector.export_json("scenario_analysis_data.json")
    
    print("\n" + "=" * 60)
    print("✅ 场面分析数据生成完成")
    print("=" * 60)
    print("\n📝 下一步：")
    print("1. 将这些数据合并到主训练数据中")
    print("2. 重新训练模型")
    print("3. 或者继续添加更多场面分析示例")


if __name__ == "__main__":
    main()
